#pragma once
//
// `.rbm` mod reader.
//
// A mod is the original program's skin-plus-soundset package: an EA-IFF-85
// CAT(PRBM) holding HEAD, INFO and 106 EMBF chunks. Counted exactly, identical
// across all four retail mods: 59 JPEG skin graphics + 46 AIFFs + 1 embedded
// Demo.rbs. Only 45 of the AIFFs are drum voices; the 46th is a Startup.aif
// chime, which both readers here correctly skip. Format decoded purely by
// inspecting mod files (see docs/FORMAT_RBM.md); no program code was used.
//
// Every embedded file is scrambled past its first 1024 bytes, so both readers
// first unscramble the archive (rbm_unscramble.h), with keys generated by
// ModPacker's key function: exact, generated in under 0.2 ms, with a first read of
// 43 to 125 ms for a whole mod, nearly all of it the self-check. Only for an
// archive they do not fit (one ModPacker did not make, one packed without a
// ModName.txt, or one edited after packing), or whose content the check cannot
// judge, are the keys estimated, which takes a few seconds more for a whole mod. Either way it
// happens the first time a given mod is read in a process and is cached after. If the unscrambled archive fails its
// self-checks, the readers return nothing and say why, so the caller plays
// without the mod instead of playing noise.
//
// This reader extracts the AUDIO only. Skin graphics are third-party artwork
// and are neither loaded nor redistributed here (see docs/SKINNING.md for the
// plan that would render them from the user's own copy).
//
#include <string>
#include <vector>
#include "reborn/engine.h"

namespace reborn {

// One voice recording extracted from a mod, under our canonical name.
struct ModSample {
    std::string name;            // canonical: "808_bd", "909_sd3", ...
    std::vector<float> data;     // mono, DC-blocked, -1..1
    int sampleRate = 44100;
};

// A mod's identity, read from its INFO chunk.
struct ModInfo {
    std::string name;          // canonical name songs reference (INFO+1003)
    std::string description;   // author/credits blurb (INFO+0)
    bool valid = false;
};

// Read a mod's identity without decoding its audio.
//
// The canonical NAME lives at INFO+1003 and is exactly the string a song's
// GLOB+15 references. Do not use the description's first line for matching:
// it disagrees for half the retail mods (MSM2's blurb says "Massens MSM 2.0"
// but songs ask for "Massen's MSM 2.0"; Orbit2's says "ReBirth Orbit 2.0"
// where songs ask for "Orbit 2.0").
ModInfo readModInfo(const std::string& rbmPath);

// Find the mod a song asks for. Scans `*.rbm` directly inside each directory
// in `searchDirs` and returns the path whose INFO name matches `skinName`
// (case-insensitive, surrounding whitespace ignored). Returns "" if no mod
// matches, including for the stock "Standard ReBirth".
std::string findModByName(const std::vector<std::string>& searchDirs,
                          const std::string& skinName);

// Extract every recognised drum voice from `rbmPath`. Returns an empty vector
// and sets `err` when the file is not a readable mod or cannot be unscrambled.
// Slow the first time a mod is read (seconds), so a caller with an audio thread
// should call this off any lock that thread takes, then installModSamples.
std::vector<ModSample> readModSamples(const std::string& rbmPath, std::string* err = nullptr);

// --- Skin graphics ---------------------------------------------------------
//
// A mod's EMBF chunks also carry its ~60 skin bitmaps. These are THIRD-PARTY
// ARTWORK: this reader hands back the encoded bytes untouched, from the user's
// own copy of their own mod, and nothing here decodes, renders or redistributes
// them. Reborn ships no mod artwork. See docs/SKINNING.md.
//
// The bytes are returned exactly as stored so a front-end can hand them to
// whatever image decoder it already has (JUCE has one; the core deliberately
// does not gain an image dependency for this).
struct ModSprite {
    std::string fileName;               // the name stored in the chunk
    std::vector<unsigned char> bytes;   // encoded image, verbatim
};

// Extract every non-audio EMBF payload from `rbmPath`, in file order.
//
// Sprite identity is the stored FILE NAME, and that name IS a numeric resource
// id ("12500.jpg", "12507.JPG"; case varies between mods). An earlier comment
// here claimed EMBF carried no resource id; that was wrong. All four retail
// mods carry the same set of 58 ids.
//
// What the container still does NOT give is image dimensions or film-strip frame
// sizes. An earlier comment here said the payloads were not standalone JPEGs
// (no SOS, no EOI, unstuffed FF bytes past the headers). That was the
// scrambling: once unscrambled, all 236 JPEGs in the four retail mods carry
// their SOS, end with their EOI and decode as ordinary images.
std::vector<ModSprite> readModSprites(const std::string& rbmPath, std::string* err = nullptr);

// Extract a mod's samples and install them into `engine`'s drum machines for
// the currently loaded song (same variant selection and snare construction as
// the directory loader). Returns the number of voices that received samples.
// Call AFTER Engine::loadSong(). Equal to installModSamples(readModSamples()).
int loadModSampleSet(Engine& engine, const std::string& rbmPath, std::string* err = nullptr);

// Install voices already read by readModSamples. Fast; this is the half to run
// under a lock the audio thread takes.
int installModSamples(Engine& engine, const std::vector<ModSample>& samples);

} // namespace reborn
