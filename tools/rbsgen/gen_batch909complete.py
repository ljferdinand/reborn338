#!/usr/bin/env python3
"""909 completeness batch (supertask 3, phase 2). See docs/COMPONENT_MATRIX.md
section 3 and docs/research/METHOD.md.

One voice per file, measured against the SAMPLE path (ReBirth's built-in 909),
effect rack and the master compressor OFF. 4-bar loop at 120 BPM, one hit every
four steps so each voice decays into silence and the step-locked windows stay
clean. The crash and ride ring for one to two seconds, so those get their own
WIDE-spaced fixtures (one hit per bar) generated by gen_batch909tails.py.

The coverage the deep dive requires, and the gaps the matrix flags:
  - BD Tune, Attack, Decay as real sweeps (four kick variants live behind Tune).
  - SD Tune (a 5-step pitch ladder), Tone, Snappy (3 noise layers), and the
    Tune x Tone x Snappy interactions at the corners.
  - LT/MT/HT INDEPENDENT Tune and Decay. Our decode currently shares one knob
    across all three (decode909Knobs reads only the LT bytes), so the mid and
    hi tom sweeps are the fixtures that will expose it.
  - Hi-hat: one shared level, separate CH and OH decays, and the CH-chokes-OH
    interaction.
  - Crash and Ride level; Crash Tune (Ride Tune is a suspected decode gap).

Usage:  python gen_batch909complete.py [outdir]
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from rbsgen import build_song, workspace_path

OUT = sys.argv[1] if len(sys.argv) > 1 else \
      workspace_path("fixtures-2026-08-25", "909complete")
os.makedirs(OUT, exist_ok=True)

TEMPO, BARS, HITS4 = 120.0, 4, [0, 4, 8, 12]

def emit(name, hits, knobs):
    path = os.path.join(OUT, name + ".rbs")
    data = build_song({}, [], tempo=TEMPO, title=name, author="rbsgen",
                      n_bars=BARS, device="909", drum_knobs=knobs, drum_hits=hits)
    with open(path, "wb") as f:
        f.write(data)
    print("  ", name + ".rbs")

# Everything silent except the voice under test (accent off, all other levels 0).
BASE = dict(accent=0, bd_level=0, sd_level=0, lt_level=0, mt_level=0,
            ht_level=0, rs_level=0, cp_level=0, hh_level=0, cr_level=0,
            rd_level=0)

def only(voice_level_key, **extra):
    k = dict(BASE); k[voice_level_key] = 100; k.update(extra); return k

FIVE  = (0, 32, 64, 96, 127)
THREE = (0, 64, 127)

print("BD: tune (the four kick variants), attack, decay (5 points each)")
for v in FIVE: emit(f"d909_bdt_{v:03d}", {"bd": HITS4}, only("bd_level", bd_tune=v,   bd_attack=64, bd_decay=64))
for v in FIVE: emit(f"d909_bda_{v:03d}", {"bd": HITS4}, only("bd_level", bd_attack=v, bd_tune=64, bd_decay=64))
for v in FIVE: emit(f"d909_bdd_{v:03d}", {"bd": HITS4}, only("bd_level", bd_decay=v,  bd_tune=64, bd_attack=64))
for v in (32, 64, 96, 127): emit(f"d909_bdl_{v:03d}", {"bd": HITS4}, only("bd_level", bd_level=v))

print("SD: tune (5-step ladder), tone, snappy (3 noise layers), 5 points each")
for v in FIVE: emit(f"d909_sdt_{v:03d}", {"sd": HITS4}, only("sd_level", sd_tune=v,   sd_tone=64, sd_snappy=64))
for v in FIVE: emit(f"d909_sdo_{v:03d}", {"sd": HITS4}, only("sd_level", sd_tone=v,   sd_tune=64, sd_snappy=64))
for v in FIVE: emit(f"d909_sds_{v:03d}", {"sd": HITS4}, only("sd_level", sd_snappy=v, sd_tune=64, sd_tone=64))

print("SD tune x tone x snappy corners (cross design; centre is sdt_064)")
for tu in (0, 127):
    for to in (0, 127):
        for sn in (0, 127):
            emit(f"d909_sdx_t{tu:03d}o{to:03d}s{sn:03d}", {"sd": HITS4},
                 only("sd_level", sd_tune=tu, sd_tone=to, sd_snappy=sn))

print("Toms: INDEPENDENT tune and decay for LT/MT/HT (exposes the shared-decode gap)")
for v in THREE: emit(f"d909_ltt_{v:03d}", {"lt": HITS4}, only("lt_level", lt_tune=v, lt_decay=64))
for v in THREE: emit(f"d909_mtt_{v:03d}", {"mt": HITS4}, only("mt_level", mt_tune=v, mt_decay=64))
for v in THREE: emit(f"d909_htt_{v:03d}", {"ht": HITS4}, only("ht_level", ht_tune=v, ht_decay=64))
for v in THREE: emit(f"d909_ltd_{v:03d}", {"lt": HITS4}, only("lt_level", lt_decay=v, lt_tune=64))
for v in THREE: emit(f"d909_mtd_{v:03d}", {"mt": HITS4}, only("mt_level", mt_decay=v, mt_tune=64))
for v in THREE: emit(f"d909_htd_{v:03d}", {"ht": HITS4}, only("ht_level", ht_decay=v, ht_tune=64))

print("Rimshot and clap (one sample each, level reference)")
emit("d909_rs_ref", {"rs": HITS4}, only("rs_level"))
emit("d909_cp_ref", {"cp": HITS4}, only("cp_level"))

print("Hats: CH and OH decay sweeps (shared HH level), plus CH+OH one step (choke)")
for v in FIVE: emit(f"d909_chd_{v:03d}", {"ch": HITS4}, only("hh_level", ch_decay=v, oh_decay=64))
for v in FIVE: emit(f"d909_ohd_{v:03d}", {"oh": HITS4}, only("hh_level", oh_decay=v, ch_decay=64))
k = dict(BASE); k["hh_level"] = 100
emit("d909_choh_same", {"ch": HITS4, "oh": HITS4}, k)

print("Crash and ride: WIDE-spaced (one hit/bar, 2 s) because the tails ring ~1-2 s.")
print("  Per the MIDI map they have Level and Tune but no Decay knob, so no decay sweep.")
HITS1 = [0]                                          # one hit per 16-step bar
emit("d909_cr_ref", {"cr": HITS1}, only("cr_level", cr_tune=64))
emit("d909_rd_ref", {"rd": HITS1}, only("rd_level", rd_tune=64))
for v in THREE: emit(f"d909_crt_{v:03d}", {"cr": HITS1}, only("cr_level", cr_tune=v))
# Ride Tune (MIDI CC 91) at header byte 28 per the shipped-song scan. This sweep
# confirms it: if ReBirth's ride pitch moves across it, byte 28 is the ride tune.
for v in THREE: emit(f"d909_rdt_{v:03d}", {"rd": HITS1}, only("rd_level", rd_tune=v))

print(f"\nWrote 909 completeness batch to {OUT}")
