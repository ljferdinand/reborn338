#!/usr/bin/env python3
"""Compressor HOLD-OUT check (clean-room, Role A, 2026-10-01).

Round 5 of the compressor (SPEC_COMP.md) fitted its detector to the material
probe (gen_comp_material.py) and its static law to the 2026-09 campaigns, and
reproduces both within 0.17 dB, but on its own data. This set is data it never
saw: new sources AND new settings, so a match here is evidence the model
generalises rather than that it was fitted well.

  sources (none in the fit):
    snare   909 snare drum on every beat
    ride    909 ride cymbal on every 8th
    cowbell 808 cowbell on every 8th
    acid    303 line with env mod, accents, slides and changing notes
    sqstac  303 square, decay 0, a note every 16th
  settings (none fitted as a pair): ratio 127 threshold 16, ratio 96
  threshold 48, ratio 112 threshold 0; and each source's compressor-off export.

Master compressor, channel fader 127, master 100, 120 BPM, 4 bars, nothing else.
Read with: python tools/measure/comp_material.py <exports> --prefix ch
No binary-analysis value is used.
"""
import argparse, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rbsgen as G

ACID_NOTES = [0, 0, 12, 0, 7, 0, 3, 10, 0, 12, 0, 5, 0, 7, 12, 3]

def acid():
    return [G.step(note=n, accent=(i % 4 == 0), slide=(i % 8 in (2, 6)))
            for i, n in enumerate(ACID_NOTES)]

def stacc():
    return [G.step(note=0) for _ in range(16)]

BASS = {
    "acid":   (dict(tune=64, cutoff=60, reso=90, envmod=100, decay=50, accent=100, waveform=0), acid),
    "sqstac": (dict(tune=64, cutoff=127, reso=0, envmod=0, decay=0, accent=0, waveform=1), stacc),
}
DRUMS = {
    "snare":   ("909", {"sd": [0, 4, 8, 12]}),
    "ride":    ("909", {"rd": [0, 2, 4, 6, 8, 10, 12, 14]}),
    "cowbell": ("808", {"cb": [0, 2, 4, 6, 8, 10, 12, 14]}),
}
SETTINGS = [("off", None), ("r127_t016", (127, 16)), ("r096_t048", (96, 48)),
            ("r112_t000", (112, 0))]

def comp(rt):
    return None if rt is None else dict(on=1, ratio=rt[0], threshold=rt[1], target=-1)

def song(src, rt, name):
    if src in BASS:
        knobs, pat = BASS[src]
        return G.build_song(knobs, pat(), tempo=120.0, n_bars=4, title=name, author="rbsgen",
                            device="bass1", comp=comp(rt), chan_vol=127)
    dev, hits = DRUMS[src]
    return G.build_song({}, [], tempo=120.0, n_bars=4, title=name, author="rbsgen",
                        device=dev, drum_hits=hits, comp=comp(rt), chan_vol=127)

def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", default=G.workspace_path("fixtures-2026-10-01", "comp-holdout"))
    a = ap.parse_args(argv); os.makedirs(a.out_dir, exist_ok=True)
    rows = []
    for src in list(BASS) + list(DRUMS):
        for tag, rt in SETTINGS:
            name = f"ch_{src}_{tag}"
            open(os.path.join(a.out_dir, name + ".rbs"), "wb").write(song(src, rt, name))
            rows.append((name, src, "compressor off" if rt is None
                         else f"master compressor, ratio {rt[0]}, threshold {rt[1]}"))
    man = ["# Compressor hold-out check (2026-10-01)", "",
           "Sources and settings the round-5 compressor fit never saw. One device,",
           "master compressor, fader 127, 120 BPM, 4 bars. Generated by",
           "`tools/rbsgen/gen_comp_holdout.py`; read with",
           "`tools/measure/comp_material.py <exports> --prefix ch`.", "",
           "| fixture | source | setting |", "|---|---|---|"]
    man += [f"| `{n}` | {s} | {w} |" for n, s, w in rows]
    open(os.path.join(a.out_dir, "MANIFEST.md"), "w", encoding="utf-8").write("\n".join(man) + "\n")
    print(f"{len(rows)} fixtures + MANIFEST.md in {a.out_dir}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
