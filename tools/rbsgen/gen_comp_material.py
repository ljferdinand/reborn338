#!/usr/bin/env python3
"""Compressor MATERIAL probe (clean-room, 2026-10-01).

The compressor was fitted on one source, a bright slid saw drone. After the
2026-10-01 topology fix, two demo songs still compress 3 to 6 dB harder than
ReBirth on other material (TGV's KiloMix, a resonant bass 1 filter sweep;
Clodhopper, 909 hits), with the uncompressed sources close. A detector that is
not RMS, or ballistics that differ, would show exactly there and nowhere in the
drone campaign. This probe holds the compressor settings and varies the SOURCE:

  steady sources, which separate detector types (an RMS, an average and a peak
  detector rank a square, a saw and a near-sine differently):
    saw     saw, cutoff 127, reso 0, slid drone (the calibration source)
    square  square, cutoff 127, reso 0, slid drone
    reso    saw, cutoff 40, reso 127, slid drone (peaky, resonant)
    dull    saw, cutoff 20, reso 0, slid drone (near-sine)
  moving sources, which separate ballistics:
    stacc   saw, cutoff 127, decay 0, a note every 16th, no slide
    kick    909 bass drum on every beat
    hats    909 closed hat on every 16th

  each at: off; ratio 127 threshold 0, 32, 64; ratio 64 threshold 0. Master
  compressor, channel fader 127, master 100, 120 BPM, 4 bars, nothing else.

Read it with tools/measure/comp_material.py, which needs only ReBirth's exports:
it feeds each uncompressed export through our compressor (comp_wav, exact for
the master path) and compares the gain reduction with ReBirth's own.
No binary-analysis value is used.
"""
import argparse, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rbsgen as G

def drone(length=16):
    return [G.step(note=0, slide=True) for _ in range(length)]

def notes(length=16):
    return [G.step(note=0) for _ in range(length)]

BASS = {
    "saw":    (dict(tune=64, cutoff=127, reso=0,   envmod=0, decay=64, accent=0, waveform=0), drone),
    "square": (dict(tune=64, cutoff=127, reso=0,   envmod=0, decay=64, accent=0, waveform=1), drone),
    "reso":   (dict(tune=64, cutoff=40,  reso=127, envmod=0, decay=64, accent=0, waveform=0), drone),
    "dull":   (dict(tune=64, cutoff=20,  reso=0,   envmod=0, decay=64, accent=0, waveform=0), drone),
    "stacc":  (dict(tune=64, cutoff=127, reso=0,   envmod=0, decay=0,  accent=0, waveform=0), notes),
}
DRUMS = {"kick": {"bd": [0, 4, 8, 12]}, "hats": {"ch": list(range(16))}}
SETTINGS = [("off", None), ("r127_t000", (127, 0)), ("r127_t032", (127, 32)),
            ("r127_t064", (127, 64)), ("r064_t000", (64, 0))]

def comp(rt):
    return None if rt is None else dict(on=1, ratio=rt[0], threshold=rt[1], target=-1)

def song(src, rt, name):
    if src in BASS:
        knobs, pat = BASS[src]
        return G.build_song(knobs, pat(), tempo=120.0, n_bars=4, title=name, author="rbsgen",
                            device="bass1", comp=comp(rt), chan_vol=127)
    return G.build_song({}, [], tempo=120.0, n_bars=4, title=name, author="rbsgen",
                        device="909", drum_hits=DRUMS[src], comp=comp(rt), chan_vol=127)

def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", default=G.workspace_path("fixtures-2026-10-01", "comp-material"))
    a = ap.parse_args(argv); os.makedirs(a.out_dir, exist_ok=True)
    rows = []
    for src in list(BASS) + list(DRUMS):
        for tag, rt in SETTINGS:
            name = f"cm_{src}_{tag}"
            open(os.path.join(a.out_dir, name + ".rbs"), "wb").write(song(src, rt, name))
            rows.append((name, src, "compressor off" if rt is None
                         else f"master compressor, ratio {rt[0]}, threshold {rt[1]}"))
    man = ["# Compressor material probe (2026-10-01)", "",
           "Same compressor settings, different sources, to separate the detector",
           "type and the ballistics from the static law. One device, master",
           "compressor, fader 127, 120 BPM, 4 bars. Generated by",
           "`tools/rbsgen/gen_comp_material.py`; read with `tools/measure/comp_material.py`.", "",
           "| fixture | source | setting |", "|---|---|---|"]
    man += [f"| `{n}` | {s} | {w} |" for n, s, w in rows]
    open(os.path.join(a.out_dir, "MANIFEST.md"), "w", encoding="utf-8").write("\n".join(man) + "\n")
    print(f"{len(rows)} fixtures + MANIFEST.md in {a.out_dir}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
